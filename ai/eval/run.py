"""Evaluation harness.   python -m ai.eval.run   [--template]

Runs every question in ai/eval/questions.jsonl through the analyst (AI mode if a key is configured, else template mode),
prints a table and writes ai/eval/report.md. Metrics are reported honestly; questions are not tuned to pass.
  fact rate        all expected facts appear in answer + findings (case-insensitive)
  citation rate    every expected source investigation appears in the cited evidence
  refusal rate     off-topic / injection questions answered with the exact refusal string
  insufficient     questions that must say "Insufficient validated experimental evidence" do
  probability      count of chance/probability/confidence wording in outputs (must be 0)
  number failures  guardrail events where generated numbers were not in the evidence
"""
import json
import statistics
import sys
import time
from pathlib import Path

from ai import config, guardrails as G
from ai.chat import analyze

HERE = Path(__file__).resolve().parent


def main() -> int:
    if "--template" in sys.argv:
        config.set_llm("none")
    qs = [json.loads(l) for l in open(HERE / "questions.jsonl", encoding="utf-8") if l.strip()]
    rows, lat = [], []
    for q in qs:
        t = time.time()
        try:
            r = analyze(q["question"])
            err = None
        except Exception as e:  # report, don't hide
            r, err = {"answer": "", "findings": [], "evidence": [], "guardrails": [], "mode": "error", "interpretation": [], "followups": []}, repr(e)
        lat.append((time.time() - t) * 1000)
        text = " ".join([r["answer"]] + r["findings"] + r.get("interpretation", []))
        facts_ok = all(f.lower() in text.lower() for f in q.get("expected_facts", []))
        cited = {e.get("acronym") for e in r["evidence"]} | {e.get("investigation_id") for e in r["evidence"]}
        cite_ok = all(s in cited for s in q.get("expected_sources", []))
        refusal_ok = (r["answer"] == G.OFF_TOPIC) if q.get("expect_refusal") else None
        insuff_ok = r["answer"].startswith(G.INSUFFICIENT) if q.get("expect_insufficient") else None
        probs = G.no_probability_violations(text + " " + " ".join(r.get("followups", [])))
        numfail = sum(1 for g in r.get("guardrails", []) if g.startswith("unsupported_numbers"))
        rows.append(dict(id=q["id"], category=q["category"], mode=r["mode"], facts=facts_ok, citations=cite_ok, refusal=refusal_ok,
                         insufficient=insuff_ok, probability=len(probs), number_failures=numfail, ms=round(lat[-1]), error=err,
                         question=q["question"], answer=r["answer"][:160]))
    pct = lambda xs: f"{100 * sum(xs) / len(xs):.0f}% ({sum(xs)}/{len(xs)})" if xs else "n/a"
    fact = [r["facts"] for r in rows if not r["refusal"] is not None or r["category"] not in ("off_topic", "injection")]
    fact = [r["facts"] for r in rows if r["category"] not in ("off_topic", "injection")]
    cite = [r["citations"] for r in rows if r["category"] not in ("off_topic", "injection")]
    ref = [r["refusal"] for r in rows if r["refusal"] is not None]
    ins = [r["insufficient"] for r in rows if r["insufficient"] is not None]
    lat_sorted = sorted(lat)
    p95 = lat_sorted[min(len(lat_sorted) - 1, int(round(0.95 * (len(lat_sorted) - 1))))]
    summary = {
        "mode": ", ".join(sorted({r["mode"] for r in rows})), "questions": len(rows),
        "answer contains expected facts": pct(fact), "citation correct": pct(cite), "off-topic / injection refusal": pct(ref),
        "insufficient-evidence when required": pct(ins), "probability violations (must be 0)": sum(r["probability"] for r in rows),
        "number-validator failures": sum(r["number_failures"] for r in rows), "errors": sum(1 for r in rows if r["error"]),
        "latency p50 ms": round(statistics.median(lat)), "latency p95 ms": round(p95),
    }
    w = max(len(k) for k in summary)
    print("\nAstroFire AI evaluation")
    for k, v in summary.items():
        print(f"  {k:<{w}}  {v}")
    fails = [r for r in rows if not r["facts"] or not r["citations"] or r["refusal"] is False or r["insufficient"] is False or r["probability"] or r["error"]]
    print(f"\n  failures: {len(fails)}")
    for r in fails:
        print(f"   - {r['id']} [{r['category']}] facts={r['facts']} cites={r['citations']} refusal={r['refusal']} "
              f"insufficient={r['insufficient']} prob={r['probability']} err={r['error']}\n     Q: {r['question']}\n     A: {r['answer']}")
    md = ["# AstroFire AI evaluation report", "", f"Generated by `python -m ai.eval.run` on {time.strftime('%Y-%m-%d %H:%M')}.", "",
          "| metric | value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary.items()]
    md += ["", "## Per question", "", "| id | category | mode | facts | citations | refusal | insufficient | prob | ms |", "|---|---|---|---|---|---|---|---|---|"]
    md += [f"| {r['id']} | {r['category']} | {r['mode']} | {r['facts']} | {r['citations']} | {r['refusal']} | {r['insufficient']} | {r['probability']} | {r['ms']} |" for r in rows]
    md += ["", "## Failures", ""] + ([f"- **{r['id']}** {r['question']} -> {r['answer']}" for r in fails] or ["- none"])
    (HERE / "report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"\n  wrote {HERE / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
